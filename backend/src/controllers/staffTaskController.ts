// Start task
export const startTask = async (req: AuthRequest, res: Response) => {
  try {
    const task = await StaffTask.findOne({
      _id: req.params.taskId,
      assignedTo: req.user._id
    });

    if (!task) {
      return res.status(404).json({ message: 'Task not found' });
    }

    if (task.status !== 'pending') {
      return res.status(400).json({ message: 'Task already started or completed' });
    }

    task.status = 'in_progress';
    task.startedAt = new Date();
    await task.save();

    res.json({ message: 'Task started successfully', task });
  } catch (error) {
    console.error('Start task error:', error);
    res.status(500).json({ message: 'Server error' });
  }
};

// Complete task with photo proof
export const completeTask = async (req: AuthRequest, res: Response) => {
  try {
    const { completionNotes } = req.body;
    const files = req.files as Express.Multer.File[];

    const task = await StaffTask.findOne({
      _id: req.params.taskId,
      assignedTo: req.user._id
    });

    if (!task) {
      return res.status(404).json({ message: 'Task not found' });
    }

    if (task.status !== 'in_progress' && task.status !== 'pending') {
      return res.status(400).json({ 
        message: `Cannot complete task with status: ${task.status}` 
      });
    }

    // Upload photos to local storage
    const photoUrls: string[] = [];
    if (files && files.length > 0) {
      // Files are already saved by multer with proper extensions
      for (const file of files) {
        // File path is relative to project root
        const relativePath = `/uploads/tasks/${file.filename}`;
        photoUrls.push(relativePath);
        console.log('Photo saved:', relativePath);
      }
    }

    const actualDuration = task.startedAt 
      ? Math.round((Date.now() - task.startedAt.getTime()) / 60000)
      : undefined;

    task.status = 'completed';
    task.completedAt = new Date();
    task.completionPhotos = photoUrls;
    task.completionNotes = completionNotes;
    task.actualDuration = actualDuration;
    await task.save();

    // Update staff profile statistics
    const staffProfile = await StaffProfile.findOne({ user: req.user._id });
    if (staffProfile) {
      staffProfile.performanceMetrics.tasksCompleted += 1;
      
      if (actualDuration) {
        const totalTasks = staffProfile.performanceMetrics.tasksCompleted;
        const currentAvg = staffProfile.performanceMetrics.averageCompletionTime;
        staffProfile.performanceMetrics.averageCompletionTime = 
          ((currentAvg * (totalTasks - 1)) + actualDuration) / totalTasks;
      }
      
      await staffProfile.save();
    }

    await StaffNotification.create({
      recipient: req.user._id,
      type: 'task_approved',
      title: 'Task Submitted for Verification',
      message: `Your task "${task.title}" has been submitted and is awaiting manager verification.`,
      relatedTask: task._id,
      priority: 'low'
    });

    res.json({ message: 'Task completed successfully', task });
  } catch (error) {
    console.error('Complete task error:', error);
    res.status(500).json({ message: 'Server error' });
  }
};

// Get task statistics for dashboard
export const getMyTaskStats = async (req: AuthRequest, res: Response) => {
  try {
    const [pending, inProgress, completed, rejected] = await Promise.all([
      StaffTask.countDocuments({ assignedTo: req.user._id, status: 'pending' }),
      StaffTask.countDocuments({ assignedTo: req.user._id, status: 'in_progress' }),
      StaffTask.countDocuments({ assignedTo: req.user._id, status: 'verified' }),
      StaffTask.countDocuments({ assignedTo: req.user._id, status: 'rejected' })
    ]);

    const todayStart = new Date();
    todayStart.setHours(0, 0, 0, 0);

    const completedToday = await StaffTask.countDocuments({
      assignedTo: req.user._id,
      status: { $in: ['completed', 'verified'] },
      completedAt: { $gte: todayStart }
    });

    const urgentTasks = await StaffTask.countDocuments({
      assignedTo: req.user._id,
      priority: 'urgent',
      status: { $in: ['pending', 'in_progress'] }
    });

    res.json({
      stats: {
        pending,
        inProgress,
        completed,
        rejected,
        completedToday,
        urgentTasks
      }
    });
  } catch (error) {
    console.error('Get task stats error:', error);
    res.status(500).json({ message: 'Server error' });
  }
};
