// Auto-create cleaning task when guest checks out
export const createCheckoutCleaningTask = async (bookingId: string, roomId: string) => {
  try {
    console.log('🔍 Creating checkout cleaning task for room:', roomId);
    
    const housekeepingStaff = await StaffProfile.findOne({ 
      staffType: 'housekeeping',
      isActive: true 
    }).populate('user');

    if (!housekeepingStaff) {
      console.error('❌ No housekeeping staff available');
      return null;
    }

    console.log('✅ Found housekeeping staff:', housekeepingStaff.user);

    const room = await Room.findById(roomId);
    if (!room) {
      console.error('❌ Room not found');
      return null;
    }

    console.log('✅ Found room:', room.roomNumber);

    room.status = 'cleaning';
    await room.save();

    const task = new StaffTask({
      taskType: 'cleaning',
      title: `Clean Room ${room.roomNumber}`,
      description: `Complete cleaning of Room ${room.roomNumber} after guest checkout. Ensure all surfaces, bathroom, and amenities are thoroughly cleaned.`,
      assignedTo: housekeepingStaff.user._id,
      room: roomId,
      priority: 'high',
      status: 'pending',
      dueTime: new Date(Date.now() + 2 * 60 * 60 * 1000),
      relatedBooking: bookingId,
      isAutoGenerated: true,
      autoGeneratedReason: 'Guest checkout',
      estimatedDuration: 45
    });

    await task.save();
    console.log('✅ Task created:', task._id);

    await StaffNotification.create({
      recipient: housekeepingStaff.user._id.toString(),
      type: 'task_assigned',
      title: `New Cleaning Task - Room ${room.roomNumber}`,
      message: `You have been assigned to clean Room ${room.roomNumber} after guest checkout. Priority: High`,
      relatedTask: task._id,
      priority: 'high'
    });

    console.log(`✅ Auto-generated cleaning task for Room ${room.roomNumber} and notification sent`);
    return task;
  } catch (error) {
    console.error('❌ Error creating checkout cleaning task:', error);
    return null;
  }
};

// Auto-create maintenance task
export const createMaintenanceTask = async (
  roomId: string,
  issueDescription: string,
  reportedBy: string,
  priority: 'low' | 'medium' | 'high' | 'urgent' = 'medium'
) => {
  try {
    const maintenanceStaff = await StaffProfile.findOne({ 
      staffType: 'maintenance',
      isActive: true 
    }).populate('user');

    if (!maintenanceStaff) {
      console.error('No maintenance staff available');
      return null;
    }

    const room = await Room.findById(roomId);
    if (!room) return null;

    room.status = 'maintenance';
    await room.save();

    const task = new StaffTask({
      taskType: 'maintenance',
      title: `Maintenance Required - Room ${room.roomNumber}`,
      description: issueDescription,
      assignedTo: maintenanceStaff.user._id,
      room: roomId,
      priority: priority,
      status: 'pending',
      dueTime: priority === 'urgent' 
        ? new Date(Date.now() + 1 * 60 * 60 * 1000)
        : new Date(Date.now() + 4 * 60 * 60 * 1000),
      isAutoGenerated: true,
      autoGeneratedReason: 'Maintenance request',
      estimatedDuration: 60
    });

    await task.save();

    await StaffNotification.create({
      recipient: maintenanceStaff.user._id.toString(),
      type: 'task_assigned',
      title: `New Maintenance Task - Room ${room.roomNumber}`,
      message: `Maintenance required: ${issueDescription}. Priority: ${priority}`,
      relatedTask: task._id,
      priority: priority === 'urgent' ? 'high' : 'medium'
    });

    console.log(`✅ Auto-generated maintenance task for Room ${room.roomNumber}`);
    return task;
  } catch (error) {
    console.error('Error creating maintenance task:', error);
    return null;
  }
};

// Get my tasks
export const getMyTasks = async (req: AuthRequest, res: Response) => {
  try {
    const { status, priority, type } = req.query;
    
    const query: any = { assignedTo: req.user._id };
    
    if (status) query.status = status;
    if (priority) query.priority = priority;
    if (type) query.taskType = type;

    const tasks = await StaffTask.find(query)
      .populate('room', 'roomNumber')
      .populate('assignedBy', 'firstName lastName')
      .sort({ priority: -1, dueTime: 1 });

    res.json({ tasks });
  } catch (error) {
    console.error('Get my tasks error:', error);
    res.status(500).json({ message: 'Server error' });
  }
};

